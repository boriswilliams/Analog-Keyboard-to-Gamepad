import vgamepad as vg
import time

from shared.connect import read_device

MAX_JS = 32767
MAX_IN = 339

PATH = b'\\\\?\\HID#VID_2E3C&PID_C365&MI_02#a&778027b&0&0000#{4d1e55b2-f16f-11cf-88cb-001111000030}'
WAKE = [0x1b, 0x00, 0x60, 0x56, 0x17, 0x0b, 0x8f, 0xa0, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x01, 0x00, 0x10, 0x00, 0x04, 0x01, 0x40, 0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00,0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]

SCALE_FACTOR = MAX_JS / MAX_IN

gamepad = vg.VX360Gamepad()

left = 0
right = 0
vg_x_value = 0

current_second = int(time.time())
frame_count = 0

display_fps = 0

for report in read_device(PATH, WAKE, 0):
  
  if report:

    magnitude = report[10] * 255 + report[9]
      
    if report[7] == 3:
      if report[8] == 2:  
        left = magnitude
      elif report[8] == 4:
        right = magnitude

    raw_joystick_x = right - left

    vg_x_value = int(raw_joystick_x * SCALE_FACTOR)

    vg_x_value = max(-MAX_JS-1, min(MAX_JS, vg_x_value))

    gamepad.left_joystick(x_value=vg_x_value, y_value=0)
    gamepad.update()
  
  # Display
  now_second = int(time.time())
  if now_second > current_second:
    display_fps = frame_count
    
    frame_count = 0
    current_second = now_second

  print(f'\rFPS: {display_fps}\n{' '.join([f"{x:3}" for x in report[5:15]])}\nL: {left:4} - R: {right:4} -> X: {vg_x_value:6}', end='\x1B[2A')
  
  frame_count += 1
