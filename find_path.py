import hid
import time

from shared import bcolors

VENDOR_ID = 0x2E3C
PRODUCT_ID = 0xC365

WAKE = [0x1b, 0x00, 0x10, 0x40, 0x2c, 0xec, 0x85, 0xc9, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x01, 0x00, 0x0c, 0x00, 0x04, 0x01, 0x40, 0x00, 0x00, 0x00, 0x01, 0x0d, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]

CYCLES = 1000

print(f'Finding path for {hex(VENDOR_ID)} {hex(PRODUCT_ID)}')

for d in hid.enumerate():
  if d['vendor_id'] == VENDOR_ID and d['product_id'] == PRODUCT_ID:
    
    print(f"\n{bcolors.BOLD}Attempting to connect to {bcolors.ENDC}{bcolors.UNDERLINE}{d['path']}{bcolors.ENDC}")
    
    try:
      device = hid.device()
      device.open_path(d['path'])
      device.set_nonblocking(1)
      device.send_feature_report(WAKE)

      print(f"{bcolors.OKCYAN}Wake-up packet transmitted to interface.{bcolors.ENDC}")
      
      dead_reports = 0

      while True:
        report = device.read(64)
        
        if report:
          print(f"{bcolors.OKGREEN}Raw Data Recieved: {list(report)}{bcolors.ENDC}")
          exit(0)
            
        else:
          dead_reports += 1
            
        time.sleep(0.001)

        if dead_reports >= CYCLES:
          print(f"{bcolors.FAIL}No data recieved for {CYCLES} cycles, skipping{bcolors.ENDC}")
          break
    except Exception as e:
      print(f"{bcolors.FAIL}{e}{bcolors.ENDC}")
    finally:
      device.close()
